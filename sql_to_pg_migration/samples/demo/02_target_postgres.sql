-- Demo target for sql_to_pg_migration.
-- Run with:  createdb demo_dst && psql -d demo_dst -f samples/demo/02_target_postgres.sql
DROP TABLE IF EXISTS hr.employee_address, hr.employee, hr.department, hr.country;
CREATE SCHEMA IF NOT EXISTS hr;

CREATE TABLE hr.country (
    country_id   integer PRIMARY KEY,
    country_name text    NOT NULL,
    iso_code     char(3) NOT NULL
);

CREATE TABLE hr.department (
    tenant_id     uuid    NOT NULL,
    department_id integer GENERATED ALWAYS AS IDENTITY,
    dept_name     varchar(100) NOT NULL,
    is_active     boolean NOT NULL DEFAULT true,
    PRIMARY KEY (tenant_id, department_id)
);

CREATE TABLE hr.employee (
    tenant_id     uuid    NOT NULL,
    employee_id   bigint  GENERATED BY DEFAULT AS IDENTITY,
    department_id integer NOT NULL,
    full_name     text    NOT NULL,
    email         text,
    salary        numeric(19,4),
    joined_on     timestamptz,
    updated_at    timestamptz,
    photo         bytea,
    source_system text    NOT NULL,
    name_upper    text GENERATED ALWAYS AS (upper(full_name)) STORED,
    PRIMARY KEY (tenant_id, employee_id),
    FOREIGN KEY (tenant_id, department_id) REFERENCES hr.department (tenant_id, department_id)
);

CREATE TABLE hr.employee_address (
    tenant_id           uuid    NOT NULL,
    employee_address_id integer GENERATED BY DEFAULT AS IDENTITY,
    employee_id         bigint  NOT NULL,
    city                text,
    PRIMARY KEY (tenant_id, employee_address_id),
    FOREIGN KEY (tenant_id, employee_id) REFERENCES hr.employee (tenant_id, employee_id)
);
