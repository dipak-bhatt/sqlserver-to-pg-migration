using SqlToPg.Safety;
using Npgsql;

namespace SqlToPg.Journal;

/// <summary>
/// The record of every run, kept in the target database (schema <c>sql_to_pg_journal</c> by default):
/// one <c>transfer_run</c> row per run and one <c>transfer_table</c> row per table it touched. A run row
/// is opened before the first table and closed on every exit — success, refusal or failure — so a row
/// still <c>running</c> with no live process means the process died, and the table rows show where.
/// It is also where the forecast learns the real throughput of this environment.
/// </summary>
public sealed class RunJournal(NpgsqlDataSource target, string schema)
{
    private string S => Ident.Pg(schema);

    public string Schema => schema;

    public async Task EnsureAsync(CancellationToken ct)
    {
        await using var conn = await target.OpenConnectionAsync(ct);
        await using var cmd = new NpgsqlCommand(
            $"""
             CREATE SCHEMA IF NOT EXISTS {S};
             CREATE TABLE IF NOT EXISTS {S}.transfer_run (
                 run_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 started_at   timestamptz NOT NULL DEFAULT now(),
                 finished_at  timestamptz,
                 operator     text NOT NULL,
                 command      text NOT NULL,
                 scope_value  text,
                 map_file     text,
                 map_sha256   text,
                 mode         text,
                 status       text NOT NULL DEFAULT 'running' CHECK (status IN ('running','succeeded','failed','refused')),
                 note         text
             );
             CREATE TABLE IF NOT EXISTS {S}.transfer_table (
                 run_id        bigint NOT NULL REFERENCES {S}.transfer_run (run_id) ON DELETE CASCADE,
                 target_table  text NOT NULL,
                 source_table  text NOT NULL,
                 rows_source   bigint,
                 rows_written  bigint,
                 started_at    timestamptz NOT NULL DEFAULT now(),
                 finished_at   timestamptz,
                 status        text NOT NULL DEFAULT 'running' CHECK (status IN ('running','done','failed','skipped')),
                 detail        text,
                 PRIMARY KEY (run_id, target_table)
             );
             """, conn);
        await cmd.ExecuteNonQueryAsync(ct);
    }

    public async Task<long> OpenAsync(string op, string command, string? scope, string? mapFile, string? mapSha, string? mode, CancellationToken ct)
    {
        await using var conn = await target.OpenConnectionAsync(ct);
        await using var cmd = new NpgsqlCommand(
            $"INSERT INTO {S}.transfer_run (operator, command, scope_value, map_file, map_sha256, mode) VALUES ($1,$2,$3,$4,$5,$6) RETURNING run_id", conn);
        cmd.Parameters.AddWithValue(op);
        cmd.Parameters.AddWithValue(command);
        cmd.Parameters.AddWithValue((object?)scope ?? DBNull.Value);
        cmd.Parameters.AddWithValue((object?)mapFile ?? DBNull.Value);
        cmd.Parameters.AddWithValue((object?)mapSha ?? DBNull.Value);
        cmd.Parameters.AddWithValue((object?)mode ?? DBNull.Value);
        return (long)(await cmd.ExecuteScalarAsync(ct))!;
    }

    /// <summary>Closes the run. Never throws: it runs on the failure path, where a second error would hide the first.</summary>
    public async Task CloseAsync(long runId, string status, string? note, TextWriter log)
    {
        try
        {
            await using var conn = await target.OpenConnectionAsync(CancellationToken.None);
            await using (var tables = new NpgsqlCommand(
                $"UPDATE {S}.transfer_table SET status = 'failed', finished_at = now(), detail = coalesce(detail, 'run ended') WHERE run_id = $1 AND status = 'running'", conn))
            {
                tables.Parameters.AddWithValue(runId);
                await tables.ExecuteNonQueryAsync(CancellationToken.None);
            }

            await using var cmd = new NpgsqlCommand($"UPDATE {S}.transfer_run SET status = $2, note = $3, finished_at = now() WHERE run_id = $1", conn);
            cmd.Parameters.AddWithValue(runId);
            cmd.Parameters.AddWithValue(status);
            cmd.Parameters.AddWithValue((object?)Clip(note) ?? DBNull.Value);
            await cmd.ExecuteNonQueryAsync(CancellationToken.None);
        }
        catch (Exception ex) when (ex is NpgsqlException or InvalidOperationException)
        {
            log.WriteLine($"  ! could not close journal run {runId}: {ex.Message}");
        }
    }

    public async Task TableStartedAsync(long runId, QualifiedName table, QualifiedName source, long? rowsSource, CancellationToken ct)
    {
        await using var conn = await target.OpenConnectionAsync(ct);
        await using var cmd = new NpgsqlCommand(
            $"""
             INSERT INTO {S}.transfer_table (run_id, target_table, source_table, rows_source) VALUES ($1,$2,$3,$4)
             ON CONFLICT (run_id, target_table) DO UPDATE SET started_at = now(), status = 'running', rows_source = EXCLUDED.rows_source, detail = NULL
             """, conn);
        cmd.Parameters.AddWithValue(runId);
        cmd.Parameters.AddWithValue(table.ToString());
        cmd.Parameters.AddWithValue(source.ToString());
        cmd.Parameters.AddWithValue((object?)rowsSource ?? DBNull.Value);
        await cmd.ExecuteNonQueryAsync(ct);
    }

    public async Task TableFinishedAsync(long runId, QualifiedName table, string status, long? rows, string? detail)
    {
        await using var conn = await target.OpenConnectionAsync(CancellationToken.None);
        await using var cmd = new NpgsqlCommand(
            $"UPDATE {S}.transfer_table SET status = $3, rows_written = $4, detail = $5, finished_at = now() WHERE run_id = $1 AND target_table = $2", conn);
        cmd.Parameters.AddWithValue(runId);
        cmd.Parameters.AddWithValue(table.ToString());
        cmd.Parameters.AddWithValue(status);
        cmd.Parameters.AddWithValue((object?)rows ?? DBNull.Value);
        cmd.Parameters.AddWithValue((object?)Clip(detail) ?? DBNull.Value);
        await cmd.ExecuteNonQueryAsync(CancellationToken.None);
    }

    /// <summary>
    /// The median rows/second of finished tables of 10,000 rows or more in earlier runs — this
    /// environment's own measured throughput — or null when there is no such history yet.
    /// </summary>
    public async Task<double?> MeasuredRateAsync(CancellationToken ct)
    {
        await using var conn = await target.OpenConnectionAsync(ct);
        await using var cmd = new NpgsqlCommand(
            $"""
             SELECT percentile_cont(0.5) WITHIN GROUP (ORDER BY rows_written / GREATEST(extract(epoch FROM finished_at - started_at), 0.001))
             FROM {S}.transfer_table WHERE status = 'done' AND rows_written >= 10000
             """, conn);
        try
        {
            return await cmd.ExecuteScalarAsync(ct) is double d ? d : null;
        }
        catch (PostgresException ex) when (ex.SqlState is PostgresErrorCodes.UndefinedTable or PostgresErrorCodes.InvalidSchemaName)
        {
            return null;
        }
    }

    public sealed record RunRow(long RunId, DateTime StartedAt, DateTime? FinishedAt, string Operator, string Command, string? Scope, string? Mode, string Status, string? Note, int Tables, long Rows);

    public async Task<IReadOnlyList<RunRow>> RecentAsync(int limit, CancellationToken ct)
    {
        await using var conn = await target.OpenConnectionAsync(ct);
        await using var cmd = new NpgsqlCommand(
            $"""
             SELECT r.run_id, r.started_at, r.finished_at, r.operator, r.command, r.scope_value, r.mode, r.status, r.note,
                    count(t.target_table)::int, coalesce(sum(t.rows_written), 0)::bigint
             FROM {S}.transfer_run r LEFT JOIN {S}.transfer_table t ON t.run_id = r.run_id
             GROUP BY r.run_id ORDER BY r.run_id DESC LIMIT $1
             """, conn);
        cmd.Parameters.AddWithValue(limit);
        var rows = new List<RunRow>();
        await using var r = await cmd.ExecuteReaderAsync(ct);
        while (await r.ReadAsync(ct))
        {
            rows.Add(new RunRow(r.GetInt64(0), r.GetDateTime(1), r.IsDBNull(2) ? null : r.GetDateTime(2), r.GetString(3), r.GetString(4),
                r.IsDBNull(5) ? null : r.GetString(5), r.IsDBNull(6) ? null : r.GetString(6), r.GetString(7), r.IsDBNull(8) ? null : r.GetString(8),
                r.GetInt32(9), r.GetInt64(10)));
        }

        return rows;
    }

    public sealed record TableRow(string Target, string Status, long? RowsSource, long? RowsWritten, double? Seconds, string? Detail);

    public async Task<IReadOnlyList<TableRow>> TablesOfAsync(long runId, CancellationToken ct)
    {
        await using var conn = await target.OpenConnectionAsync(ct);
        await using var cmd = new NpgsqlCommand(
            $"SELECT target_table, status, rows_source, rows_written, extract(epoch FROM finished_at - started_at)::float8, detail FROM {S}.transfer_table WHERE run_id = $1 ORDER BY started_at", conn);
        cmd.Parameters.AddWithValue(runId);
        var rows = new List<TableRow>();
        await using var r = await cmd.ExecuteReaderAsync(ct);
        while (await r.ReadAsync(ct))
        {
            rows.Add(new TableRow(r.GetString(0), r.GetString(1), r.IsDBNull(2) ? null : r.GetInt64(2), r.IsDBNull(3) ? null : r.GetInt64(3),
                r.IsDBNull(4) ? null : r.GetDouble(4), r.IsDBNull(5) ? null : r.GetString(5)));
        }

        return rows;
    }

    private static string? Clip(string? text) => text is { Length: > 4000 } ? text[..4000] + "…" : text;
}
